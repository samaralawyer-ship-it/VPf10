"""Промпты для модели."""

from __future__ import annotations

SYSTEM_PROMPT = """Ты обрабатываешь расшифровку разговора менеджера турагентства с клиентом.
Верни ТОЛЬКО JSON-объект. Без пояснений, без markdown, без ```.

Схема полей:
- client_name (строка) — имя клиента, если он его назвал; иначе "не указано";
- contact (строка) — телефон, мессенджер или почта, если звучали;
- country (строка) — страна поездки;
- city (строка) — город или курорт;
- dates (строка) — даты или период словами клиента («10–17 июля»);
- nights (целое 1–60 или null) — число ночей;
- people (целое 1–20 или null) — сколько человек едет;
- budget (число или null) — бюджет в рублях, только цифры;
- preferences (список строк, до 6) — конкретные пожелания словами клиента: «завтраки», «первая линия», «тихий район», «бассейн», «детский клуб»; не обобщай;
- topic (строка) — тема обращения одной фразой;
- main_request (строка) — суть запроса, 1–2 предложения;
- mood (строка) — настроение клиента: спокойное, заинтересованное, раздражённое и т.п.;
- risks (список строк, до 5) — риски и возражения словами клиента: «бюджет под вопросом», «нет прямых рейсов», «сомневается по датам»; без выдуманных рисков;
- next_steps (список строк, до 6) — что договорились делать дальше;
- manager (строка) — имя менеджера;
- confidence (число 0–1) — насколько уверенно данные извлечены из текста.

Правила:
- если данных в разговоре нет — для строк пиши "не указано", для чисел null;
- не выдумывай факты, которых нет в тексте;
- числа приводи к цифрам: «сто пятьдесят тысяч» → 150000;
- списки держи короткими, по одному пункту на мысль."""


def build_messages(dialog: str) -> list[dict]:
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": f"Расшифровка разговора:\n\n{dialog.strip()}"},
    ]


def repair_messages(dialog: str, bad_answer: str, error: str) -> list[dict]:
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": f"Расшифровка разговора:\n\n{dialog.strip()}"},
        {"role": "assistant", "content": (bad_answer or "")[:4000]},
        {
            "role": "user",
            "content": (
                f"Этот ответ не прошёл проверку: {error}.\n"
                "Верни исправленный JSON строго по схеме, без пояснений."
            ),
        },
    ]